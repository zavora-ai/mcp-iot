//! # mcp-iot
//!
//! MCP server for IoT device management — telemetry ingestion, remote commands,
//! alerts, digital twins, fleet management, OTA updates, and geofencing.
//!
//! ## Features
//! - Device registry (register, list, get, decommission)
//! - Telemetry ingestion and querying (time-series)
//! - Remote commands (reboot, configure, firmware update)
//! - Alert rules and triggered alerts
//! - Digital twins (shadow state)
//! - Fleet groups and bulk operations
//! - OTA firmware management
//! - Geofencing with breach detection
//!
//! ## Usage
//! ```bash
//! cargo install mcp-iot
//! ```
